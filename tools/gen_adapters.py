#!/usr/bin/env python3
"""Render the two Rivet agent roles into each host's native format.

Sources (edit these):
  adapters/roles/{coordinator,worker}.md   host-neutral role text
  adapters/hosts/<host>.md                 per-host worker launch notes

Outputs (generated; do not edit by hand):
  plugins/rivet/agents/*.md                          Claude Code
  plugins/rivet/cursor/agents/*.md                   Cursor
  plugins/rivet/com.github.copilot/agents/*.agent.md GitHub Copilot (Agent Plugins namespace)
  plugins/rivet/codex/agents/rivet_worker.toml       Codex (installed by `rivet bootstrap --host codex`)
  plugins/rivet/skills/rivet-work/references/{coordinator,worker,hosts}.md

Usage: gen_adapters.py [--check]
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADAPTERS = os.path.join(ROOT, "adapters")
PLUGIN = os.path.join(ROOT, "plugins", "rivet")
HOSTS = ("claude-code", "codex", "copilot", "cursor")
NOTICE = "Generated by tools/gen_adapters.py from adapters/; edit the sources, not this file."

WORKER_DESCRIPTION = (
    "Rivet worker: carries out one bounded implementation or investigation assignment from the Rivet "
    "coordinator and reports changed paths, validation, blockers and discoveries. Launched only by the "
    "coordinator after a dispatch reservation; never invoke it directly."
)
COORDINATOR_DESCRIPTION = (
    "Rivet coordinator for one admitted work item: holds the lease, works directly or delegates bounded "
    "tasks to rivet-worker one at a time, records evidence, and finishes with the engine. Select it as the "
    "main agent; do not launch it as a subagent."
)


def source(*parts):
    with open(os.path.join(ADAPTERS, *parts), encoding="utf-8") as handle:
        return handle.read().strip() + "\n"


def engine_line(levels):
    return (
        "**Engine:** run `rivet <command>`. If `rivet` is not on PATH, run `python3 <plugin>/bin/rivet <command>`, "
        f"where `<plugin>` is {levels} above this file. Resolve it to an absolute path once and reuse it. "
        "`rivet <command> --help` lists flags."
    )


def coordinator(engine, launch):
    return source("roles", "coordinator.md").replace("{{engine}}", engine).replace("{{launch}}", launch).rstrip() + "\n"


def launch_section(host):
    return "## Launching a worker on this host\n\n" + source("hosts", f"{host}.md")


def frontmatter(fields):
    lines = ["---"]
    for key, value in fields:
        lines.append(f"{key}: {value}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def markdown(fields, body):
    return frontmatter(fields) + f"<!-- {NOTICE} -->\n\n" + body


def toml_literal(text):
    if "'''" in text:
        raise ValueError("role text must not contain ''' for TOML literal strings")
    return "'''\n" + text + "'''"


def render():
    worker = source("roles", "worker.md")
    files = {}

    # Claude Code: plugin agents are namespaced rivet:<name>. The worker's tool
    # list leaves out Agent so it cannot spawn subagents of its own.
    files["agents/rivet-worker.md"] = markdown(
        [("name", "rivet-worker"), ("description", json.dumps(WORKER_DESCRIPTION)),
         ("tools", "Read, Write, Edit, Glob, Grep, Bash"), ("model", "inherit")],
        worker,
    )
    files["agents/rivet-coordinator.md"] = markdown(
        [("name", "rivet-coordinator"), ("description", json.dumps(COORDINATOR_DESCRIPTION)), ("model", "inherit")],
        coordinator(engine_line("one directory"), launch_section("claude-code")),
    )

    # Cursor: name, description, model.
    files["cursor/agents/rivet-worker.md"] = markdown(
        [("name", "rivet-worker"), ("description", json.dumps(WORKER_DESCRIPTION)), ("model", "inherit")],
        worker,
    )
    files["cursor/agents/rivet-coordinator.md"] = markdown(
        [("name", "rivet-coordinator"), ("description", json.dumps(COORDINATOR_DESCRIPTION)), ("model", "inherit")],
        coordinator(engine_line("two directories"), launch_section("cursor")),
    )

    # GitHub Copilot: hide the worker from the picker, keep it out of the agent
    # tool set, and let the coordinator call only the worker.
    files["com.github.copilot/agents/rivet-worker.agent.md"] = markdown(
        [("name", "rivet-worker"), ("description", json.dumps(WORKER_DESCRIPTION)),
         ("tools", "['read', 'edit', 'search', 'execute']"), ("user-invocable", "false")],
        worker,
    )
    files["com.github.copilot/agents/rivet-coordinator.agent.md"] = markdown(
        [("name", "rivet-coordinator"), ("description", json.dumps(COORDINATOR_DESCRIPTION)),
         ("agents", "['rivet-worker']"), ("disable-model-invocation", "true")],
        coordinator(engine_line("two directories"), launch_section("copilot")),
    )

    # Codex: one standalone TOML file per custom agent.
    files["codex/agents/rivet_worker.toml"] = (
        f"# {NOTICE}\n"
        'name = "rivet_worker"\n'
        f"description = {json.dumps(WORKER_DESCRIPTION)}\n"
        f"developer_instructions = {toml_literal(worker)}\n"
    )

    # Skill references, loaded only when the work skill needs them.
    files["skills/rivet-work/references/worker.md"] = f"<!-- {NOTICE} -->\n\n# Rivet worker brief\n\n" + worker
    files["skills/rivet-work/references/coordinator.md"] = (
        f"<!-- {NOTICE} -->\n\n# Rivet coordinator protocol\n\n"
        + coordinator(
            "**Engine:** use it exactly as the rivet-work skill locates it.",
            "## Launching a worker\n\nFollow your host's entry in `hosts.md` next to this file. If your host is not "
            "listed or cannot launch a subagent, delegation is unavailable: work directly.\n",
        )
    )
    files["skills/rivet-work/references/hosts.md"] = (
        f"<!-- {NOTICE} -->\n\n# Launching one worker, per host\n\n"
        "Reserve with `dispatch` first, launch exactly one worker, wait, then `settle-dispatch`. "
        "Use the `--adapter` value shown for your host.\n\n"
        + "\n".join(source("hosts", f"{host}.md") for host in HOSTS)
    )
    return files


def main(argv):
    check = "--check" in argv
    stale = []
    for rel, content in sorted(render().items()):
        path = os.path.join(PLUGIN, rel)
        try:
            with open(path, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current == content:
            continue
        stale.append(rel)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(content)
    if check and stale:
        print("stale generated files (run tools/gen_adapters.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    if not check:
        print(f"wrote {len(stale)} file(s)" if stale else "up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
