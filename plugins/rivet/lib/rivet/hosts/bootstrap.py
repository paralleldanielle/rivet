"""`rivet bootstrap`: install what host plugin systems cannot carry, and initialize the target repository.

It never overwrites a file that is not Rivet's, never runs a host's own CLI,
and with --dry-run changes nothing.
"""

import os

from .. import config, configure
from ..errors import RivetError
from ..workspace import Workspace

HOSTS = ("claude-code", "codex", "copilot", "cursor")
PLUGIN_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__)))))
REPO_URL = "paralleldanielle/rivet"
GENERATED = "# Generated by tools/gen_adapters.py"
BEGIN, END = "<!-- rivet:begin -->", "<!-- rivet:end -->"


def _hosts(selected):
    if not selected:
        return []
    if "all" in selected:
        return list(HOSTS)
    return [h for h in HOSTS if h in selected]


def _symlink(path, target, dry_run, actions):
    action = {"action": "symlink", "path": path, "target": target}
    if os.path.islink(path) and os.path.realpath(path) == os.path.realpath(target):
        action["status"] = "exists"
    elif os.path.lexists(path):
        action["status"] = "conflict"
        action["detail"] = "a different file already exists here; left untouched"
    elif dry_run:
        action["status"] = "would_create"
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        os.symlink(target, path)
        action["status"] = "created"
    actions.append(action)
    return action


def _write_generated(path, content, dry_run, actions):
    action = {"action": "write", "path": path}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as handle:
            current = handle.read()
        if current == content:
            action["status"] = "exists"
        elif current.startswith(GENERATED):
            action["status"] = "would_update" if dry_run else "updated"
        else:
            action["status"] = "conflict"
            action["detail"] = "an unrelated file already exists here; left untouched"
    else:
        action["status"] = "would_create" if dry_run else "created"
    if action["status"] in ("created", "updated"):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content)
    actions.append(action)
    return action


def _block(context_dir):
    return (
        f"{BEGIN}\n"
        "## Rivet\n\n"
        "This repository tracks bounded agent work with Rivet. At the start of a session, check `rivet status` "
        "(the rivet-status skill) before resuming anything. Implementation requests go through the rivet-work "
        f"skill; human-owned intent lives in `{context_dir}`. The latest human instruction always takes priority "
        "over persisted Rivet work.\n"
        f"{END}\n"
    )


def _upsert_block(path, block, dry_run, actions):
    action = {"action": "instructions", "path": path}
    text = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    if BEGIN in text and END in text:
        start, end = text.index(BEGIN), text.index(END) + len(END)
        updated = text[:start] + block.rstrip("\n") + text[end:]
    else:
        updated = text + ("\n" if text and not text.endswith("\n") else "") + ("\n" if text else "") + block
    if updated == text:
        action["status"] = "exists"
    elif dry_run:
        action["status"] = "would_update" if text else "would_create"
    else:
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(updated)
        action["status"] = "updated" if text else "created"
    actions.append(action)


def _repo_writes_allowed(ws):
    """Writing files into the repository changes the baseline of admitted work."""
    if not ws.db_exists():
        return
    conn = ws.connect()
    active = [r["work_id"] for r in conn.execute(
        "SELECT c.work_id FROM contracts c JOIN work_items w ON w.id = c.work_id "
        "WHERE w.state NOT IN ('completed', 'abandoned')")]
    if active:
        raise RivetError(
            "repo_writes_blocked",
            "writing bootstrap files into the repository would change the baseline of unfinished admitted work: "
            + ", ".join(active),
        )


def _next_steps(hosts):
    marketplace_root = os.path.dirname(os.path.dirname(PLUGIN_ROOT))
    local_marketplace = os.path.exists(os.path.join(marketplace_root, ".claude-plugin", "marketplace.json"))
    steps = {}
    if "claude-code" in hosts:
        steps["claude-code"] = [
            f"/plugin marketplace add {marketplace_root if local_marketplace else REPO_URL}",
            "/plugin install rivet@rivet",
            f"or, for one session: claude --plugin-dir {PLUGIN_ROOT}",
        ]
    if "copilot" in hosts:
        steps["copilot"] = [
            f"Copilot CLI: copilot plugin marketplace add {marketplace_root if local_marketplace else REPO_URL}",
            "Copilot CLI: copilot plugin install rivet@rivet",
            f"VS Code: run 'Chat: Install Plugin From Source' with https://github.com/{REPO_URL}",
        ]
    if "codex" in hosts:
        steps["codex"] = [
            f"codex plugin marketplace add {marketplace_root if local_marketplace else REPO_URL}",
            "then open /plugins in Codex and install rivet",
        ]
    if "cursor" in hosts:
        steps["cursor"] = ["reload Cursor; the plugin is linked under ~/.cursor/plugins/local/rivet"]
    return steps


def run(args, launcher):
    hosts = _hosts(args.host)
    dry_run = args.dry_run
    home = os.path.expanduser("~")
    actions = []
    result = {"plugin_root": PLUGIN_ROOT, "hosts": hosts, "dry_run": dry_run, "actions": actions}

    needs_repo = (not args.no_init) or args.instructions or (args.scope == "project" and "codex" in hosts)
    ws = Workspace(cwd=args.repo, launcher=launcher) if needs_repo else None
    try:
        if ws is not None and (args.instructions or (args.scope == "project" and "codex" in hosts)):
            _repo_writes_allowed(ws)

        if args.link_bin:
            directory = os.path.abspath(os.path.expanduser(args.link_bin))
            action = _symlink(os.path.join(directory, "rivet"), os.path.join(PLUGIN_ROOT, "bin", "rivet"), dry_run, actions)
            action["on_path"] = directory in os.environ.get("PATH", "").split(os.pathsep)

        if "codex" in hosts:
            source = os.path.join(PLUGIN_ROOT, "codex", "agents", "rivet_worker.toml")
            with open(source, encoding="utf-8") as handle:
                content = handle.read()
            base = ws.root if args.scope == "project" else home
            _write_generated(os.path.join(base, ".codex", "agents", "rivet_worker.toml"), content, dry_run, actions)

        if "cursor" in hosts:
            _symlink(os.path.join(home, ".cursor", "plugins", "local", "rivet"), PLUGIN_ROOT, dry_run, actions)

        if not args.no_init:
            if dry_run:
                actions.append({"action": "init", "path": ws.root, "status": "would_run"})
            else:
                outcome = configure.init(ws)
                actions.append({"action": "init", "path": ws.root, "status": "done", "created": outcome["created"],
                                "warnings": outcome["warnings"]})

        if args.instructions:
            cfg = ws.read_config() or config.default_config()
            block = _block(cfg["context_dir"])
            targets = []
            if not hosts or any(h in hosts for h in ("codex", "copilot", "cursor")):
                targets.append("AGENTS.md")
            if not hosts or "claude-code" in hosts:
                targets.append("CLAUDE.md")
            for name in targets:
                _upsert_block(os.path.join(ws.root, name), block, dry_run, actions)
    finally:
        if ws is not None:
            ws.close()

    result["next_steps"] = _next_steps(hosts)
    result["conflicts"] = [a["path"] for a in actions if a["status"] == "conflict"]
    return result

